// Mechanical asset build: preserve original PNGs and furniture dimensions.
// Run with sharp installed (or set NODE_PATH to the bundled node_modules).
const fs = require('node:fs/promises');
const path = require('node:path');
const crypto = require('node:crypto');
const sharp = require('sharp');
const {pathToFileURL} = require('node:url');

const root = path.resolve(__dirname, '..');
const web = path.join(root, 'docs/games/ast-home');
const out = path.join(web, 'assets/optimized');

// Match the two original renderers exactly, including their odd-size splits.
function bounds(data, width, height, threshold) {
  return [0, 1, 2, 3].map(n => {
    const x0 = Math.floor(n % 2 * width / 2);
    const y0 = Math.floor(Math.floor(n / 2) * height / 2);
    const x1 = threshold === 30 ? Math.floor(x0 + width / 2) : Math.floor((n % 2 + 1) * width / 2);
    const y1 = threshold === 30 ? Math.floor(y0 + height / 2) : Math.floor((Math.floor(n / 2) + 1) * height / 2);
    let l = x1, r = x0, t = y1, b = y0;
    for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) {
      if (data[(y * width + x) * 4 + 3] > threshold) {
        l = Math.min(l, x); r = Math.max(r, x); t = Math.min(t, y); b = Math.max(b, y);
      }
    }
    if (r < l || b < t) throw new Error('Empty sprite quadrant');
    return {x: l, y: t, w: r - l + 1, h: b - t + 1};
  });
}

async function main() {
  const {scanAtlas} = await import(pathToFileURL(path.join(web, 'sprite-geometry.mjs')));
  await fs.mkdir(out, {recursive: true});
  const manifest = {};
  for (const dir of ['backgrounds', 'furniture', 'house', 'ui']) {
    const names = (await fs.readdir(path.join(web, 'assets', dir))).filter(n => n.endsWith('.png')).sort();
    for (const name of names) {
      const original = `assets/${dir}/${name}`, file = path.join(web, original);
      const input = await fs.readFile(file), meta = await sharp(input).metadata();
      let pipeline = sharp(input);
      const coin = dir === 'ui';
      if (coin) pipeline = pipeline.resize(96, 96, {fit: 'inside', withoutEnlargement: true});
      const {data, info} = await pipeline.webp({quality: 88, alphaQuality: 100, effort: 6, smartSubsample: true}).toBuffer({resolveWithObject: true});
      const hash = crypto.createHash('sha256').update(data).digest('hex').slice(0, 12);
      const output = `${name.slice(0, -4)}-${hash}.webp`;
      await fs.writeFile(path.join(out, output), data);
      const entry = {url: `assets/optimized/${output}`, width: info.width, height: info.height,
        bytes: data.length, originalBytes: input.length,
        originalSha256: crypto.createHash('sha256').update(input).digest('hex')};
      if (name.endsWith('-4dir.png')) {
        const rgba = await sharp(input).ensureAlpha().raw().toBuffer();
        entry.frames30 = bounds(rgba, meta.width, meta.height, 30);
        entry.frames40 = bounds(rgba, meta.width, meta.height, 40);
        entry.framesRegistered = scanAtlas(rgba, meta.width, meta.height);
        // Alpha is lossless: precomputed sprite rectangles stay pixel-exact.
        const encoded = await sharp(data).ensureAlpha().raw().toBuffer();
        for (let i = 3; i < rgba.length; i += 4) {
          if (rgba[i] !== encoded[i]) throw new Error(`Alpha changed: ${original}`);
        }
      }
      if (coin) await fs.writeFile(path.join(out, 'ast-coin-small-v1.webp'), data);
      manifest[original] = entry;
      console.log(`${original}: ${input.length} -> ${data.length} bytes`);
    }
  }
  await fs.writeFile(path.join(web, 'asset-manifest.mjs'),
    '// Generated by tool/optimize_ast_home_assets.cjs. Keep the original PNGs.\n' +
    'export const ASSETS = ' + JSON.stringify(manifest, null, 2) + ';\n');
  const summary = Object.values(manifest).reduce((r, a) => ({original: r.original + a.originalBytes, optimized: r.optimized + a.bytes}), {original: 0, optimized: 0});
  console.log(JSON.stringify(summary));
}

if (require.main === module) main().catch(e => {console.error(e); process.exitCode = 1;});
module.exports = {bounds};
